begin;

create table if not exists public.products (
  id text primary key,
  name text not null,
  description text not null,
  category text not null check (category in ('Chêne', 'Hêtre', 'Frêne', 'Charme', 'Mélange')),
  stock numeric(10, 2) not null default 0 check (stock >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_prices (
  product_id text not null references public.products(id) on delete cascade,
  log_length text not null check (log_length in ('25 cm', '33 cm', '40 cm', '50 cm', '1 m')),
  price_per_m3 numeric(10, 2) not null check (price_per_m3 >= 0),
  primary key (product_id, log_length)
);

create table if not exists public.product_images (
  id bigint generated by default as identity primary key,
  product_id text not null references public.products(id) on delete cascade,
  path text not null,
  is_primary boolean not null default false,
  created_at timestamptz not null default now()
);

create unique index if not exists one_primary_image_per_product
  on public.product_images(product_id) where is_primary;

create table if not exists public.orders (
  id text primary key,
  customer_name text not null,
  phone text not null,
  email text not null,
  postal_code text not null,
  address text not null,
  delivery_notes text not null default '',
  items jsonb not null,
  delivery_fee numeric(10, 2) not null default 0 check (delivery_fee >= 0),
  total numeric(10, 2) not null check (total >= 0),
  status text not null default 'new'
    check (status in ('new', 'confirmed', 'delivered', 'cancelled')),
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.product_prices enable row level security;
alter table public.product_images enable row level security;
alter table public.orders enable row level security;

